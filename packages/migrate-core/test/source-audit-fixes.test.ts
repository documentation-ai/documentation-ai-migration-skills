/**
 * What running real starter repositories through the whole migration found, one source at a time:
 * the official Docusaurus template stopped at inventory, the Mintlify starter at nav, and Nextra's
 * own docs held most of their pages. Each case here is the smallest form of one of those.
 */
import { describe, it, expect } from 'vitest';
import { mkdirSync, mkdtempSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { markdownToIr } from '../src/ir/from-markdown.js';
import { docToMdx } from '../src/ir/to-dai-mdx.js';
import { RulesEngine, applyDeclaredLosses, loadMappings } from '../src/components/rules-engine.js';
import { Ledger } from '../src/ledger/dispositions.js';
import { DecisionLog } from '../src/log/decisions.js';
import { ensureWorkspace } from '../src/session/workspace.js';
import { asksOnlyForAutogeneratedSidebar, readDocusaurusRepo } from '../src/adapters/docusaurus.js';
import { mintlifyBranding } from '../src/scrape/site-branding.js';
import { readMintlifyRepo } from '../src/adapters/mintlify.js';
import { siteLinksFor, siteLinkResolver } from '../src/urls/site-links.js';
import { authoredContentSnapshot, fidelityEqual } from '../src/verify/fidelity.js';
import type { Tree } from '../src/nav/tree.js';

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), '..', '..', '..');
const write = (root: string, file: string, body: string): void => { mkdirSync(join(root, dirname(file)), { recursive: true }); writeFileSync(join(root, file), body); };
const tables = (platform: string) => [join(repoRoot, `skills/migrate-generic-to-documentation-ai/mappings/${platform}.yaml`), join(repoRoot, 'skills/migrate-generic-to-documentation-ai/mappings/generic.yaml')];

function convert(source: string, platform: string) {
  const w = mkdtempSync(join(tmpdir(), 'dai-audit-fixes-')); ensureWorkspace(w);
  const engine = new RulesEngine({ platform, mappings: loadMappings(platform === 'docusaurus' ? [tables('generic')[1]] : tables(platform)), ledger: new Ledger(w), log: new DecisionLog(w) });
  const doc = markdownToIr(source, { platform, file: 'docs/page.mdx', pageId: 'p', title: 'Page' });
  const resolved = engine.resolveDoc(doc);
  // compared as verify compares: the source read through the losses its approved rules declare
  return { doc: applyDeclaredLosses(doc, engine), resolved, mdx: docToMdx(resolved) };
}

describe('Docusaurus', () => {
  it('reads titled admonitions (3) and their older spelling (2), and never writes a closer without an opener', () => {
    const { mdx, doc, resolved } = convert(':::tip[My tip]\n\nUse this.\n\n:::\n\n:::danger Take care\n\nDangerous.\n\n:::\n\n```md\n:::tip[Inside code]\n:::\n```\n\nA stray closer:\n\n:::\n', 'docusaurus');
    expect(mdx).toMatch(/<Callout kind="tip">\s+\*\*My tip\*\*\s+Use this\./);
    expect(mdx).toMatch(/<Callout kind="danger">\s+\*\*Take care\*\*\s+Dangerous\./);
    expect(mdx).toContain(':::tip[Inside code]');
    expect(fidelityEqual(authoredContentSnapshot(doc), authoredContentSnapshot(resolved))).toBe(true);
  });

  it('keeps a heading id written as an MDX comment as the anchor, and other comments as written', () => {
    const doc = markdownToIr('## Headings {/* #my-heading-id */}\n\nText {/* a note */} here.\n', { platform: 'docusaurus', file: 'docs/x.mdx', pageId: 'p' });
    expect(doc.children[0]).toMatchObject({ type: 'heading', sourceId: 'my-heading-id' });
    expect(JSON.stringify(doc.children[0])).not.toContain('/*');
    expect(JSON.stringify(doc.children[1])).toContain('{/* a note */}');
  });

  it('drops MDX import and export lines, which define what a page uses and are never its content', () => {
    const { mdx } = convert("import Tabs from '@theme/Tabs';\n\nexport const Highlight = ({children}) => <span>{children}</span>;\n\nHello.\n", 'docusaurus');
    expect(mdx).not.toMatch(/QUARANTINED|import Tabs|export const/);
    expect(mdx).toContain('Hello.');
  });

  it('reads the sidebars file every new site starts with as the autogenerated sidebar, and nothing else', () => {
    expect(asksOnlyForAutogeneratedSidebar("// @ts-check\nconst sidebars = {\n  tutorialSidebar: [{type: 'autogenerated', dirName: '.'}],\n  // manual:\n  /* tutorialSidebar: ['intro'], */\n};\nexport default sidebars;\n")).toBe(true);
    expect(asksOnlyForAutogeneratedSidebar("module.exports = { docs: ['intro', {type: 'autogenerated', dirName: '.'}] };")).toBe(false);
    const root = mkdtempSync(join(tmpdir(), 'dai-docusaurus-'));
    write(root, 'package.json', JSON.stringify({ dependencies: { '@docusaurus/core': '3.9.0' } }));
    write(root, 'sidebars.js', "const sidebars = { tutorialSidebar: [{type: 'autogenerated', dirName: '.'}] };\nexport default sidebars;\n");
    write(root, 'docs/intro.md', '---\nsidebar_position: 1\n---\n\n# Intro\n\nHi.\n');
    const repo = readDocusaurusRepo(root);
    expect(repo.sidebarsFile).toBeUndefined();
    expect(repo.tree.navigationSource).toBe('source-config');
  });
});

describe('links a repository page writes to another page\'s file', () => {
  it('resolve to that page\'s route', () => {
    const tree: Tree = { scope: 'full', platform: 'docusaurus', pages: [
      { id: 'a', title: 'A', source: 'docs/basics/a.mdx', group: [], order: 0, oldPath: '/basics/a', newPath: 'basics/a', migrate: true },
      { id: 'b', title: 'B', source: 'docs/extras/b.mdx', group: [], order: 1, oldPath: '/extras/b', newPath: 'extras/b', migrate: true },
    ] };
    const resolve = siteLinkResolver(siteLinksFor(tree));
    expect(resolve('../extras/b.mdx#part', 'docs/basics/a.mdx')).toMatchObject({ target: '/extras/b#part', kind: 'route' });
  });
});

describe('Nextra', () => {
  it('titles each tab from the parent\'s items, and converts callouts by their type', () => {
    const { mdx, doc, resolved } = convert("import { Callout, Tabs } from 'nextra/components'\n\n<Tabs items={['pnpm', 'C++']} defaultIndex={1}>\n  <Tabs.Tab>\n  pnpm i\n  </Tabs.Tab>\n  <Tabs.Tab>\n  g++\n  </Tabs.Tab>\n</Tabs>\n\n<Callout type=\"warning\" emoji=\"⚠️\">\nCareful.\n</Callout>\n\n<Callout>\nPlain.\n</Callout>\n", 'nextra');
    expect(mdx).toContain('<Tab title="pnpm">');
    expect(mdx).toContain('<Tab title="C++">');
    expect([...mdx.matchAll(/<Callout kind="(\w+)">/g)].map((m) => m[1])).toEqual(['alert', 'info']);
    expect(mdx).not.toMatch(/QUARANTINED|data-source-component/);
    expect(fidelityEqual(authoredContentSnapshot(doc), authoredContentSnapshot(resolved))).toBe(true);
  });

  it('keeps an anchor written as an empty span, which an older link still lands on', () => {
    const { mdx, doc, resolved } = convert('<span id="older-anchor" />\n\n## Today\n\nText.\n', 'nextra');
    expect(mdx).toContain('<a id="older-anchor"></a>');
    expect(fidelityEqual(authoredContentSnapshot(doc), authoredContentSnapshot(resolved))).toBe(true);
  });
});

describe('Mintlify', () => {
  it('carries links pinned above every sidebar (navigation.global) as top-bar links, not as navigation', () => {
    const root = mkdtempSync(join(tmpdir(), 'dai-mintlify-'));
    const config = { name: 'Starter', navigation: { pages: [{ group: 'Getting Started', pages: ['index'] }], global: { anchors: [{ anchor: 'Blog', href: 'https://acme.com/blog', icon: 'newspaper' }] } } };
    write(root, 'docs.json', JSON.stringify(config));
    write(root, 'index.mdx', '---\ntitle: Introduction\n---\n\nHi.\n');
    const repo = readMintlifyRepo(root);
    expect(repo.tree.navigation!.map((node) => node.type === 'group' ? node.label : node.pageId)).toEqual(['Getting Started']);
    expect(mintlifyBranding(config as Record<string, unknown>)?.navbar?.links).toEqual([{ title: 'Blog', link: 'https://acme.com/blog' }]);
  });
});
